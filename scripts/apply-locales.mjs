// apply-locales.mjs — 把翻译产出（hn-orig-check/i18n-work/）合并进站点词典
// 产出: scripts/locales-es.mjs / scripts- locales-ar.mjs（数据词典） + src/lib/ui-locales.ts（UI 按键）
// 用法: node scripts/apply-locales.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";

const WORK = "C:/Users/Administrator/ZCodeProject/hn-orig-check/i18n-work/";
const readJson = (f) => JSON.parse(readFileSync(WORK + f, "utf8"));

// 1. 短句词典（含主批次 tr-short-* 与增量 tr-delta-*）
function loadShort(prefix) {
  const files = readdirSync(WORK).filter((f) => f.startsWith(prefix) && f.endsWith(".json")).sort();
  const out = {};
  for (const f of files) Object.assign(out, readJson(f));
  return out;
}
const esShort = loadShort("tr-");
const arShort = loadShort("ar-");

// 2. 长文（新闻正文）按 pairs-long.json 的顺序 i ↔ body-i.<lang>.md
const longEntries = readJson("pairs-long.json");
function loadBodies(lang) {
  const out = {};
  for (const [i, { en }] of Object.entries(longEntries)) {
    let md = readFileSync(WORK + `body-${i}.${lang}.md`, "utf8").trim();
    if (md.startsWith("# ENTRY") || md.includes("## EN")) throw new Error(`body-${i}.${lang}.md 含未清理的模板头`);
    out[en] = md;
  }
  return out;
}
const esLong = loadBodies("es");
const arLong = loadBodies("ar");

const TR_ES = { ...esShort, ...esLong };
const TR_AR = { ...arShort, ...arLong };

// 3. UI 按键
const UI_ES = readJson("ui.json");
const UI_AR = readJson("ar-ui.json");

// 4. 覆盖率校验（对照 dump 清单）
const dump = JSON.parse(readFileSync("C:/Users/Administrator/ZCodeProject/hn-orig-check/to-translate.json", "utf8"));
const needData = Object.keys(dump.pairs);
const needUi = Object.keys(dump.ui);
const missEs = needData.filter((k) => !(k in TR_ES));
const missAr = needData.filter((k) => !(k in TR_AR));
const missUiEs = needUi.filter((k) => !(k in UI_ES));
const missUiAr = needUi.filter((k) => !(k in UI_AR));
console.log(`data coverage: es ${needData.length - missEs.length}/${needData.length}, ar ${needData.length - missAr.length}/${needData.length}`);
console.log(`ui coverage:   es ${needUi.length - missUiEs.length}/${needUi.length}, ar ${needUi.length - missUiAr.length}/${needUi.length}`);
if (missEs.length) console.log("MISSING ES:", missEs.slice(0, 10));
if (missAr.length) console.log("MISSING AR:", missAr.slice(0, 10));
if (missUiEs.length) console.log("MISSING UI-ES:", missUiEs.slice(0, 10));
if (missUiAr.length) console.log("MISSING UI-AR:", missUiAr.slice(0, 10));

// 译文与原文相同的（多为符号/缩写，属正常；列出供人工复核）
const sameEs = needData.filter((k) => TR_ES[k] === k).length;
const sameAr = needData.filter((k) => TR_AR[k] === k).length;
console.log(`identical-to-en (symbols expected): es ${sameEs}, ar ${sameAr}`);

// 5. 写出（整对象 JSON.stringify 内嵌，天然处理反引号/${转义）
writeFileSync(
  new URL("./locales-es.mjs", import.meta.url),
  `// 西语译文词典（按英文原文索引）。由 scripts/apply-locales.mjs 生成，勿手改。\nexport const TR = ${JSON.stringify(TR_ES, null, 1)};\n`,
  "utf8"
);
writeFileSync(
  new URL("./locales-ar.mjs", import.meta.url),
  `// 阿拉伯语译文词典（按英文原文索引）。由 scripts/apply-locales.mjs 生成，勿手改。\nexport const TR = ${JSON.stringify(TR_AR, null, 1)};\n`,
  "utf8"
);
writeFileSync(
  new URL("../src/lib/ui-locales.ts", import.meta.url),
  `// UI dictionary translations for es/ar, keyed by ui key (see i18n.ts).\n// GENERATED by scripts/apply-locales.mjs — do not edit by hand.\n// Keys absent here fall back to the English text in i18n.ts.\n\nexport const UI_ES: Record<string, string> = ${JSON.stringify(UI_ES, null, 1)};\n\nexport const UI_AR: Record<string, string> = ${JSON.stringify(UI_AR, null, 1)};\n`,
  "utf8"
);
console.log("written: scripts/locales-es.mjs, scripts/locales-ar.mjs, src/lib/ui-locales.ts");
